using System;
using System.Collections;
using System.Collections.Generic;
using System.Reflection;
using Mortal.Core;
using UnityEngine;
using UnityEngine.UI;

namespace DiceMaster.Information
{
    public static partial class InformationAnchors
    {
        private const BindingFlags Fields = BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public;
        private static readonly FieldInfo positionTitle = typeof(PositionOptionButton).GetField("_titleText", Fields);
        private static readonly FieldInfo breakTitle = typeof(BreakOptionButton).GetField("_titleText", Fields);
        private static readonly FieldInfo textCache = typeof(Text).GetField("m_TextCache", Fields);
        private static readonly FieldInfo[] positionGraphics = Graphics(typeof(PositionOptionButton), "_typeText", "_titleText", "_descText", "_iconImage");
        private static readonly FieldInfo[] breakGraphics = Graphics(typeof(BreakOptionButton), "_typeText", "_titleText", "_actionText", "_contributeText");
        private struct CardGeometry { internal Rect Title, Body; internal bool HasTitle, HasBody; }
        private static readonly Dictionary<object, CardGeometry> cardGeometry = new Dictionary<object, CardGeometry>();
        private static bool painting;
        internal static void BeginPaint() { cardGeometry.Clear(); painting = true; }
        internal static void EndPaint() { painting = false; cardGeometry.Clear(); }
        public static bool IsCard(object anchor) { return anchor is PositionOptionButton || anchor is BreakOptionButton; }
        private static FieldInfo[] Graphics(Type type, params string[] names)
        {
            var fields = new FieldInfo[names.Length];
            for (int at = 0; at < names.Length; at++) fields[at] = type.GetField(names[at], Fields);
            return fields;
        }
        private static Rect Union(Rect a, Rect b) { return InformationLayout.IncludingBadge(a, b); }
        // Read the Text mesh already generated by Unity. The public generator
        // getter can allocate a generator; preferredWidth/Populate can force
        // text generation. Neither is used, and no native layout is changed.
        private static bool GlyphRect(Text label, Camera fallback, out Rect rect)
        {
            rect = default(Rect);
            if (!Live(label) || string.IsNullOrEmpty(label.text) || textCache == null) return false;
            var generator = textCache.GetValue(label) as TextGenerator;
            var rt = label.transform as RectTransform;
            if (generator == null || rt == null) return false;
            IList<UIVertex> vertices = generator.verts;
            if (vertices == null || vertices.Count < 4 || vertices.Count > 1024 || vertices.Count % 4 != 0) return false;
            float unit = 1f / label.pixelsPerUnit;
            if (!Finite(unit) || unit <= 0) return false;
            Vector2 first = new Vector2(vertices[0].position.x * unit, vertices[0].position.y * unit);
            Vector2 adjusted = label.PixelAdjustPoint(first);
            float left = float.MaxValue, right = float.MinValue, bottom = float.MaxValue, top = float.MinValue;
            bool found = false;
            for (int at = 0; at < vertices.Count; at += 4)
            {
                float x0 = float.MaxValue, x1 = float.MinValue, y0 = float.MaxValue, y1 = float.MinValue;
                for (int n = 0; n < 4; n++)
                {
                    Vector3 p = vertices[at + n].position;
                    if (!Finite(p.x) || !Finite(p.y)) return false;
                    x0 = Math.Min(x0, p.x); x1 = Math.Max(x1, p.x); y0 = Math.Min(y0, p.y); y1 = Math.Max(y1, p.y);
                }
                // Spaces and the generator's terminal quad have no ink.
                if (x1 <= x0 || y1 <= y0) continue;
                left = Math.Min(left, x0); right = Math.Max(right, x1); bottom = Math.Min(bottom, y0); top = Math.Max(top, y1); found = true;
            }
            if (!found) return false;
            Canvas canvas = label.GetComponentInParent<Canvas>();
            if (canvas != null) canvas = canvas.rootCanvas;
            bool overlay = canvas != null && canvas.renderMode == RenderMode.ScreenSpaceOverlay;
            Camera projection = overlay ? null : canvas != null && canvas.worldCamera != null ? canvas.worldCamera : fallback;
            if (!overlay && projection == null) return false;
            float offsetX = adjusted.x - first.x, offsetY = adjusted.y - first.y;
            corners[0] = rt.TransformPoint(new Vector3(left * unit + offsetX, bottom * unit + offsetY, 0));
            corners[1] = rt.TransformPoint(new Vector3(left * unit + offsetX, top * unit + offsetY, 0));
            corners[2] = rt.TransformPoint(new Vector3(right * unit + offsetX, top * unit + offsetY, 0));
            corners[3] = rt.TransformPoint(new Vector3(right * unit + offsetX, bottom * unit + offsetY, 0));
            left = bottom = float.MaxValue; right = top = float.MinValue;
            foreach (Vector3 corner in corners)
            {
                if (!Finite(corner.x) || !Finite(corner.y) || !Finite(corner.z) || projection != null && projection.WorldToScreenPoint(corner).z <= 0) return false;
                Vector2 p = RectTransformUtility.WorldToScreenPoint(projection, corner);
                if (!Finite(p.x) || !Finite(p.y)) return false;
                left = Math.Min(left, p.x); right = Math.Max(right, p.x); bottom = Math.Min(bottom, p.y); top = Math.Max(top, p.y);
            }
            rect = new Rect(left, Screen.height - top, right - left, top - bottom);
            return rect.width > 0 && rect.height > 0;
        }
        private static CardGeometry Card(object anchor)
        {
            CardGeometry value;
            if (painting && cardGeometry.TryGetValue(anchor, out value)) return value;
            value = default(CardGeometry);
            try
            {
                var component = anchor as Component;
                if (!Live(component)) return value;
                Camera projection = CameraFor(component);
                value.HasBody = ComponentRect(component, projection, out value.Body);
                var fields = anchor is PositionOptionButton ? positionGraphics : breakGraphics;
                foreach (FieldInfo field in fields)
                {
                    object graphic = field == null ? null : field.GetValue(anchor);
                    var list = graphic as IList;
                    for (int at = 0; at < (list == null ? 1 : Math.Min(12, list.Count)); at++)
                    {
                        Rect next;
                        if (!ComponentRect((list == null ? graphic : list[at]) as Component, projection, out next)) continue;
                        value.Body = value.HasBody ? Union(value.Body, next) : next; value.HasBody = true;
                    }
                }
                FieldInfo title = anchor is PositionOptionButton ? positionTitle : breakTitle;
                var labels = title == null ? null : title.GetValue(anchor) as Text[];
                if (labels != null) for (int at = 0; at < Math.Min(12, labels.Length); at++)
                {
                    Rect next;
                    if (!GlyphRect(labels[at], projection, out next)) continue;
                    value.Title = value.HasTitle ? Union(value.Title, next) : next; value.HasTitle = true;
                }
            }
            catch (Exception) { value.HasTitle = false; }
            if (painting) cardGeometry[anchor] = value;
            return value;
        }
        public static bool TryCardRect(object anchor, out Rect rect)
        {
            rect = default(Rect); if (!IsCard(anchor)) return false;
            CardGeometry value = Card(anchor); rect = value.Body; return value.HasBody;
        }
        public static bool TryBadgeRect(object anchor, float size, bool map, out Rect rect)
        {
            rect = default(Rect);
            var viewport = new Rect(0, 0, Screen.width, Screen.height);
            if (!map && IsCard(anchor))
            {
                CardGeometry card = Card(anchor);
                if (!card.HasTitle) return false;
                rect = InformationLayout.InlineBadge(card.Title, viewport, size); return true;
            }
            Rect area;
            if (!TryRect(anchor, out area)) return false;
            rect = InformationLayout.Badge(area, viewport, size, map); return true;
        }
    }
}
